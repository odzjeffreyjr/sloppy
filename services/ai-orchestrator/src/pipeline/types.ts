import type { GenerationPhase } from '@sloppy/shared';
import type { GameGenre, GameEngine } from '@sloppy/runtime-sdk';

// ---------------------------------------------------------------------------
// Game Design Document (GDD) — output of the Concept Architect agent
// ---------------------------------------------------------------------------

export interface GameDesignDocument {
  title: string;
  logline: string;
  engine: GameEngine;
  genre: GameGenre;
  template?: string;
  visualStyle: string;
  coreMechanic: string;
  controls: Array<{ key: string; action: string }>;
  progression: string;
  scoring: string;
  gameOverCondition: string;
  restartBehavior: string;
  screens: {
    intro: string;
    hud: string;
    pause: string;
    gameOver: string;
  };
  multiplayer: {
    suitable: boolean;
    mode?: 'competitive' | 'cooperative' | 'versus';
    description?: string;
    maxPlayers?: number;
    syncStrategy?: 'state-sync' | 'input-relay' | 'lockstep';
  };
  objects: Array<{ name: string; description: string }>;
  complexity: 'simple' | 'medium' | 'complex';
  estimatedGenerationTimeSeconds: number;
}

// ---------------------------------------------------------------------------
// Technical Spec — output of the Technical Planner agent
// ---------------------------------------------------------------------------

export interface TechnicalSpec {
  fileStructure: string;
  engineVersion: string;
  /** Template name to use as base, or null if building from scratch. */
  useTemplate?: string | null;
  /** If useTemplate is set, describes what the Code Generator must change/add. */
  templateCustomizations?: string | null;
  modules: Array<{ name: string; responsibility: string }>;
  criticalApis: string[];
  performanceConstraints: string[];
  sdkV2Mapping: {
    init: string;
    start: string;
    pause: string;
    resume: string;
    restart: string;
    destroy: string;
  };
}

// ---------------------------------------------------------------------------
// V1 backward-compat types
// ---------------------------------------------------------------------------

/**
 * @deprecated Replaced by GameDesignDocument in v2 pipeline.
 * Kept as adapter for any remaining v1 references.
 */
export interface GameConcept {
  title: string;
  description: string;
  mechanics: string[];
  visualStyle: string;
  supportsMultiplayer: boolean;
  assets: Array<{
    name: string;
    description: string;
    type: 'emoji' | 'shape' | 'svg';
  }>;
  controls: string;
  winCondition: string;
  difficulty: 'easy' | 'medium' | 'hard';
}

/** Converts a GDD to the legacy GameConcept shape for backward compat. */
export function gddToGameConcept(gdd: GameDesignDocument): GameConcept {
  return {
    title: gdd.title,
    description: gdd.logline,
    mechanics: [gdd.coreMechanic],
    visualStyle: gdd.visualStyle,
    supportsMultiplayer: gdd.multiplayer.suitable,
    assets: gdd.objects.map((o) => ({
      name: o.name,
      description: o.description,
      type: 'svg' as const,
    })),
    controls: gdd.controls.map((c) => `${c.key}: ${c.action}`).join(', ') || 'keyboard',
    winCondition: gdd.gameOverCondition,
    difficulty:
      gdd.complexity === 'simple'
        ? 'easy'
        : gdd.complexity === 'complex'
          ? 'hard'
          : 'medium',
  };
}

// ---------------------------------------------------------------------------
// Asset / Bundle types (unchanged)
// ---------------------------------------------------------------------------

export interface GeneratedAsset {
  name: string;
  svg: string;
  width: number;
  height: number;
}

export interface GameBundle {
  html: string;
  /** @deprecated In v2, all code is inline in the HTML. Kept for backward compat. */
  js: string;
  config: {
    title: string;
    version: string;
    engine?: GameEngine;
    genre?: GameGenre;
    supportsMultiplayer: boolean;
    maxPlayers?: number;
    assets: string[];
    audio: string[];
  };
  assets: GeneratedAsset[];
}

// ---------------------------------------------------------------------------
// Pipeline Context
// ---------------------------------------------------------------------------

export interface PipelineContext {
  sessionId: string;
  userId: string;
  prompt: string;

  gdd?: GameDesignDocument;
  spec?: TechnicalSpec;

  /** @deprecated Use gdd instead. Populated via gddToGameConcept for backward compat. */
  concept?: GameConcept;
  gameCode?: string;
  assets?: GeneratedAsset[];
  /** Audio files generated by the Audio Generator (ElevenLabs mode only). */
  audioFiles?: Array<{ name: string; data: Buffer; mimeType: string }>;
  /** AI-generated thumbnail buffers (WebP) from FLUX + Sharp compositor. */
  thumbnailBuffer?: Buffer;
  thumbnailSmBuffer?: Buffer;
  /** Screenshots from the last successful validation run (base64). */
  lastValidationScreenshots?: Record<string, string>;
  bundle?: GameBundle;

  tokenUsage: {
    promptTokens: number;
    completionTokens: number;
    totalTokens: number;
    byPhase: Record<string, { promptTokens: number; completionTokens: number }>;
  };
}

// ---------------------------------------------------------------------------
// Phase / Progress types
// ---------------------------------------------------------------------------

export interface PhaseResult {
  phase: GenerationPhase;
  success: boolean;
  error?: string;
}

export type ProgressCallback = (
  phase: GenerationPhase,
  progress: number,
  message: string,
) => void;
